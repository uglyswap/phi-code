			const cwd = ctx?.cwd || process.cwd();
			const sandbox = getSessionSandbox(cwd);
			const result = sandbox.exec(p.command, {
				timeoutMs: Math.max(1, Math.min(1800, p.timeoutSeconds ?? 300)) * 1000,
			});
			const verdict = !sandbox.available()
				? "UNAVAILABLE"
				: result.timedOut
					? "TIMEOUT"
					: passed(result)
						? "PASS"
						: "FAIL";
