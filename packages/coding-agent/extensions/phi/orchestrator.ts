	/**
	 * Resolve a routing.json model reference to an available model.
	 * Accepts a provider-qualified "provider/id" reference (so the same model id
	 * offered by several providers can be disambiguated) and falls back to a bare
	 * "id" for legacy configs. Splits on the FIRST slash only, since some model
	 * ids themselves contain slashes (e.g. OpenRouter "anthropic/claude-...").
	 */
	function resolveModelRef(available: any[], ref: string): any | undefined {
		if (!ref) return undefined;
		const slash = ref.indexOf("/");
		if (slash > 0) {
			const provider = ref.slice(0, slash);
			const id = ref.slice(slash + 1);
			const qualified = available.find((m: any) => m.provider === provider && m.id === id);
			if (qualified) return qualified;
		}
		return available.find((m: any) => m.id === ref);
	}

	/**
	 * Switch model for the current phase.
	 * Returns the model id actually in use plus an optional warning when the
	 * requested routing.json model could not be applied (not in registry or no
	 * API key), so the caller can surface the degraded routing to the user.
	 */
	async function switchModelForPhase(
		phase: OrchestratorPhase,
		ctx: any,
	): Promise<{ modelId: string; warning?: string }> {
		const available = ctx.modelRegistry?.getAvailable?.() || [];
		// On a retry, resolve the fallback FIRST so we swap to a different model
		// (ideally another family) rather than re-hitting the one that just failed.
		const target = phase.useFallback
			? resolveModelRef(available, phase.fallback) || resolveModelRef(available, phase.model)
			: resolveModelRef(available, phase.model) || resolveModelRef(available, phase.fallback);
		const currentId = ctx.model?.id || phase.model;

		if (!target) {
			// Neither the preferred nor the fallback ref resolved to a registered model.
			return {
				modelId: currentId,
				warning: `Phase ${phase.label} model '${phase.model}' unavailable (not in registry); running on '${currentId}'`,
			};
		}

		if (target.id !== ctx.model?.id || target.provider !== ctx.model?.provider) {
			const switched = await pi.setModel(target);
			if (switched) return { modelId: target.id };
			// setModel returns false when the target has no configured auth.
			return {
				modelId: currentId,
				warning: `Phase ${phase.label} model '${phase.model}' unavailable (no API key); running on '${currentId}'`,
			};
		}
		return { modelId: target.id };
	}

